import type { CompareMode, Difficulty, Param, Problem, Signature, ValueType } from '../types';

/* Built-in problems carry a language-neutral signature + test inputs.
   Expected outputs live in expected.json, generated from reference solutions
   (scripts/reference.py) so they are never hand-typed. */

function params(spec: string): Param[] {
  if (!spec.trim()) return [];
  return spec.split(',').map((s) => {
    const [name, type] = s.split(':').map((x) => x.trim());
    return { name, type: type as ValueType };
  });
}
const fn = (name: string, p: string, returns: ValueType, mutates?: number): Signature => ({ kind: 'function', name, params: params(p), returns, mutates });

interface BuiltinSpec {
  id: string; title: string; topic: string; pattern: string; difficulty: Difficulty;
  summary: string; statement: string; constraints?: string[]; sig: Signature;
  tests: unknown[][]; samples?: number; compare?: CompareMode; hints?: string[];
}
const B = (s: BuiltinSpec): Problem => ({
  id: s.id, title: s.title, topic: s.topic, pattern: s.pattern, difficulty: s.difficulty,
  summary: s.summary, statement: s.statement.trim(), constraints: s.constraints, signature: s.sig,
  tests: s.tests.map((input, i) => ({ input, sample: i < (s.samples ?? 2) })),
  compare: s.compare ?? 'exact', hints: s.hints, builtin: true,
  url: `https://leetcode.com/problems/${s.id}/`,
});
const X = (id: string, title: string, topic: string, pattern: string, difficulty: Difficulty, summary: string, url?: string): Problem => ({
  id, title, topic, pattern, difficulty, summary, builtin: false,
  url: url ?? `https://leetcode.com/problems/${id}/`,
});

